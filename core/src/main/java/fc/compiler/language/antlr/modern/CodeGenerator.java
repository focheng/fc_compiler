	/**
	 * case only keywords/literal: idDivision : (IDENTIFICATION | ID) DIVISION '.'
	 * case nested rules:          statement: ifStatement | forStatement | returnStatement
	 * case keywords & multiple:   thenStatement : NEXT SENTENCE | statement*
	 */
	public Void visit(Alternatives node, Object p) {
		List<Expression> list = node.children().stream().filter(expr -> !isMultipleQuantified(expr)
								&& !isRuleOfAlternative(expr)).toList();
		String tokenKindList = buildIdentifiableTokenKindList(list);
		if (node.children().size() == list.size()) { // only keywords or literals
			String acceptOrOptional = isOptional(toQuantifiedType(p)) ? "optionalAnyOf" : "acceptAnyOf";
			sbParser.append(String.format("reader.%s(%s);", acceptOrOptional, tokenKindList)).append(lineSeparator);
		} else {
			List<Expression> multipleQuantifiedList = node.children().stream().filter(expr -> isMultipleQuantified(expr)).toList();
			List<Expression> subRuleIsAlternativeList = node.children().stream().filter(expr -> isRuleOfAlternative(expr)).toList();
			if (1 == multipleQuantifiedList.size() && 0 == subRuleIsAlternativeList.size()) {
				String acceptOrOptional = isOptional(toQuantifiedType(p)) ? "optionalAnyOf" : "acceptAnyOf";
				sbParser.append(String.format("if (reader.%s(%s)) {", acceptOrOptional, tokenKindList)).append(lineSeparator);
				sbParser.append("} else {");
				visit(multipleQuantifiedList.get(0), p);
				sbParser.append("}");
			} else if (1 == subRuleIsAlternativeList.size() && 0 == multipleQuantifiedList.size()) {
			} else {
				System.out.println("No implemented for " + node.toString());
				for (Expression expr: node.children()) {
					expr.accept(this, p);
				}
			}
		}

		return null;
	}

	private static boolean isMultipleQuantified(Expression expr) {
		return expr instanceof QuantifiedExpression qe && qe.isMultiple();
	}

	private boolean isRuleOfAlternative(Expression expr) {
		return expr instanceof Identifier id
				&& rules.containsKey(id.id())
				&& rules.get(id.id()).expression() instanceof Alternatives;
	}

	private String buildIdentifiableTokenKindList(List<Expression> expressions) {
		List<IdentifiableToken> tokenList = finder.getIdentifiableTokenList(expressions);
		if (tokenList.size() == 0) {
			return "";
		}
		return tokenList.get(0).alternatives.stream().collect(Collectors.joining(", "));
	}

	/**
	 * An identifier can be
	 * - a rule name defined in grammar file;
	 * - a token kind if all letters are uppercase like WHILE
	 * - a normal identifier.
	 */
	public Void visit(Identifier node, Object p) {
		visit(node, p, false);
		return null;
	}

	public Void visit(Identifier node, Object p, boolean returnIdentifier) {
		String code = null;
		String id = node.id();
		if (StrUtils.isAllUpperCase(id)) {
			String quantifiedType = toQuantifiedType(p);
			String acceptOrOptional = isOptional(quantifiedType) ? "optional" : "accept";
			code = String.format("reader.%s(%s);", acceptOrOptional, id);
		} else if (rules.containsKey(id)) {
			code = String.format("result.%s(parse%s(reader, registry));", id, StringUtils.capitalize(id));
		} else {
			if (returnIdentifier) {
				code = "Identifier result = parseIdentifier(reader, registry);";
			} else {
				code = String.format("result.%s(parseIdentifier(reader, registry));", id);
			}
		}
		sbParser.append(indent2).append(code).append(lineSeparator);
		return null;
	}

	public Void visit(Literal node, Object p) {
		String quantifiedType = toQuantifiedType(p);
		String key = String.valueOf(node.value());
		sbParser.append(indent2);
		if (mapStringLiteral2TokenKind.containsKey(key)) {
			String acceptOrOptional = isOptional(quantifiedType) ? "optional" : "accept";
			sbParser.append(String.format("reader.%s(%s);", acceptOrOptional, mapStringLiteral2TokenKind.get(key))).append(lineSeparator);
		} else {
			sbParser.append("parseLiteral(reader, registry);").append(lineSeparator);
		}
		return null;
	}

	public Void visit(QuantifiedExpression node, Object p) {
		switch (node.quantifierType()) {
			case "?":   visit(node.expression(), node.quantifierType());    break;
			case "*":
			case "+":
				buildQuantified(node.expression());
				break;
		}
		return null;
	}

	protected Identifier asIdentifier(Expression expr) {
		if (expr instanceof Identifier id)
			return id;
		if (expr instanceof QuantifiedExpression qe && qe.expression() instanceof Identifier id)
			return id;
		return null;
	}

	private void buildQuantified(Expression expr) {
		if (expr instanceof Identifier id) {
			if (StrUtils.isAllUpperCase(id.id())) {
				// ignore token kind.
			}
			boolean isDefinedRule = rules.containsKey(id.id());

			String variableName = id.id();
			String typeName = isDefinedRule
					? StringUtils.capitalize(variableName)
					: Identifier.class.getName().equalsIgnoreCase(variableName)
						? variableName
						: "Expression";

			String methodName = "parse" + typeName + "List";
			sbParser.append(indent2)
					.append(String.format("List<%s> %sList = %s", typeName, variableName, methodName))
					.append(ARGUMENTS_READER_REGISTRY).append(";").append(lineSeparator);
			sbParser.append(indent2).append(String.format("result.%sList(%sList);", variableName, variableName)).append(lineSeparator);

			buildParseListMethod(variableName, typeName, methodName);
		} else {
			System.out.println("buildQuantified does not support " + expr);
		}
	}

	private void buildParseListMethod(String variableName, String typeName, String methodName) {
		if (methods.containsKey(methodName))
			return ;

		StringBuilder sb = new StringBuilder();
		sb.append(String.format("public static List<%s> %s(TokenReader reader, ParserRegistry registry) {", typeName, methodName)).append(lineSeparator);
		sb.append(indent).append(String.format("List<%s> list = new ArrayList<>();", typeName)).append(lineSeparator);
		sb.append(indent).append("while (true) {").append(lineSeparator);
		sb.append(indent).append(indent).append(String.format("%s o = parse%s(reader, registry);", typeName, typeName)).append(lineSeparator);
		sb.append(indent).append(indent).append("if (o == null) break;").append(lineSeparator);
		sb.append(indent).append(indent).append("list.add(o);").append(lineSeparator);
		sb.append(indent).append("};").append(lineSeparator);
		sb.append(indent).append("return list;").append(lineSeparator);
		sb.append("}").append(lineSeparator);
		methods.put(methodName, sb.toString());
	}

