	@Override
	public String toString() {
		StringBuilder sb = new StringBuilder();
		sb.append(HEADER).append(lineSeparator);
		sb.append(STR."public class \{parserClassName} extends ParserBase {").append(lineSeparator);
		sb.append(buildParserRegistry());
		sb.append(sbParser.toString());
		for (String method : methods.values()) {
			sb.append(method).append(lineSeparator);
		}
		sb.append("}").append(lineSeparator);
		return sb.toString();
	}

	private String buildParserRegistry() {
		StringBuilder sb = new StringBuilder();
		sb.append(indent).append("public static ParserRegistry initRegistry() {").append(lineSeparator);
		sb.append(indent2).append("ParserRegistry map = new ParserRegistry();").append(lineSeparator);
		for (String parserRegistration : statementParsers) {
			sb.append(indent2).append(parserRegistration).append(lineSeparator);
		}
		sb.append(indent2).append("return map;").append(lineSeparator);
		sb.append(indent).append("}").append(lineSeparator);
		return sb.toString();
	}

	public Void visit(Rule rule, Object p) {
		String ruleName = rule.name().id();
		String returnType = StringUtils.capitalize(ruleName);
		List<IdentifiableToken> tokenList = getIdentifiableTokenList(ruleName);
		// ignore it because ParserBase already has it.
		if ("statement".equalsIgnoreCase(ruleName)) {
//			rule.expression()
			return null;
		}

		String quickTest = buildQuickTestForRule(tokenList);

		RuleFeatureAnalyzer.RuleFeature feature = featureAnalyzer.mapRule2Feature.get(ruleName);
		boolean enableOptimization = !ruleName.endsWith("Statement") && !ruleName.endsWith("Expression");
		if (enableOptimization
				&& rule.expression() instanceof Sequence sequence
				&& !feature.hasMultipleToReturn()) {
			buildMethod(sequence, p, ruleName, quickTest);
			return null;
		}
//		if (rule.expression() instanceof Sequence sequence
//				&& hasOnlyOneRuleInSequence(sequence)) {
//			buildInlineSequence(sequence, p, ruleName);
//			return null;
//		}

		sbParser.append(indent).append(STR."public static \{returnType} parse\{returnType}\{PARAMETERS_READER_REGISTRY}\n");
		if (quickTest != null && !quickTest.isEmpty())
			sbParser.append(indent2).append(STR."if (!\{quickTest}) return null;\n");
		sbParser.append("\n");
		if (rule.expression() == null) {    // blank. e.g. ruleA: ;
			sbParser.append(indent2).append("return null;").append(lineSeparator);
		} else {
			sbParser.append(indent2).append(STR."\{returnType} result = new \{returnType}();\n");
			rule.expression().accept(this, p);
			sbParser.append(indent2).append("return result;\n");
		}
		sbParser.append(indent).append("}\n");

		if (ruleName.endsWith("Statement")) {
			if (tokenList.size() == 1) {
				if (tokenList.get(0).alternatives() == null) {
					String tokenKind = tokenList.get(0).tokenKind();
					statementParsers.add(STR."map.put(\{tokenKind}, \{parserClassName}::parse\{returnType});");
				} else {
					for (String tokenKind : tokenList.get(0).alternatives()) {
						statementParsers.add(STR."map.put(\{tokenKind}, \{parserClassName}::parse\{returnType});");
					}
				}
			}
		}

		return null;
	}

	/**
	 * If a rule contains at most one Identifier, just return this Identifier
	 * to avoid creating a new ASTNode class.
	 */
	private void buildMethod(Sequence node, Object p, String ruleName, String quickTest) {
		sbParser.append(indent).append(String.format("public static Identifier parse%s%s",
				StringUtils.capitalize(ruleName), PARAMETERS_READER_REGISTRY)).append(lineSeparator);
		if (quickTest != null && !quickTest.isEmpty())
			sbParser.append(indent2).append(STR."if (!\{quickTest}) return null;\n");

		for (Expression expr : node.children()) {
			if (expr instanceof Identifier id) {
				visit(id, p, true);
			} else {
				visit(expr, p);
			}
		}
		sbParser.append(indent2).append("return result;").append(lineSeparator);
		sbParser.append(indent).append("}").append(lineSeparator);
	}

	private String buildQuickTestForRule(List<IdentifiableToken> tokenList) {
		if (tokenList.size() == 1) {
			if (tokenList.get(0).alternatives() == null) {
				String tokenKind = tokenList.get(0).tokenKind();
				return STR."reader.isKind(\{tokenKind})";
			} else {
				String tokenKinds = tokenList.get(0).alternatives().toString();
				tokenKinds = tokenKinds.substring(1, tokenKinds.length()-1);
				return STR."reader.isKindAnyOf(\{tokenKinds})";
			}
		}
		return "";
	}

	private List<IdentifiableToken> getIdentifiableTokenList(String ruleName) {
		List<IdentifiableToken> tokenList = finder.rule2IdentifiableTokenList.get(ruleName);
		if (tokenList == null) {
			finder.visit(rules.get(ruleName), null);
			tokenList = finder.rule2IdentifiableTokenList.get(ruleName);
		}
		return tokenList;
	}

	public Void visit(Sequence node, Object p) {
		for (Expression expr : node.children()) {
			expr.accept(this, p);
		}
		return null;
	}

